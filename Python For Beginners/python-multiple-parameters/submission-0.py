def two_sum(
    addend_1: int,
    addend_2: int,
):
    print(addend_1 + addend_2)

def three_sum(
    addend_1: int,
    addend_2: int,
    addend_3: int,
):
    print(addend_1 + addend_2 + addend_3)

two_sum(7, 10)
three_sum(3, 5, 8)

